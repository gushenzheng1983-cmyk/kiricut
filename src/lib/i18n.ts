const dict = { zh, ja, en };

export function t(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  let text: string = dict[locale][key] ?? dict.zh[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function getZoneLabelI18n(locale: Locale, zone: string): string {
  const map: Record<string, TranslationKey> = {
    "top-left": "zoneTopLeft",
    "bottom-right": "zoneBottomRight",
    center: "zoneCenter",
    custom: "zoneCustom",
    auto: "zoneAuto",
  };
  return t(locale, map[zone] ?? "zoneAuto");
}

