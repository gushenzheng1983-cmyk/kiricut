import { readFileSync, writeFileSync } from "fs";
import { execSync } from "child_process";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

let gitSha = "unknown";
try {
  gitSha = execSync("git rev-parse --short HEAD", {
    cwd: root,
    stdio: ["ignore", "pipe", "ignore"],
  })
    .toString()
    .trim();
} catch {
  /* not a git repo */
}

const content = `/** Auto-generated by scripts/write-build-info.mjs — do not edit */
export const APP_VERSION = ${JSON.stringify(pkg.version)};
export const BUILD_SHA = ${JSON.stringify(gitSha)};
export const BUILD_TIME = ${JSON.stringify(new Date().toISOString())};
`;

writeFileSync(join(root, "src/lib/buildInfo.ts"), content);
console.log(`build-info: v${pkg.version} @ ${gitSha}`);
